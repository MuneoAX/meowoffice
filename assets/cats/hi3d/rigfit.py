def make(name, bones, src='cat_rig'):
    s = bpy.data.objects[src]
    old = bpy.data.objects.get(name)
    if old:
        arm = old.data; bpy.data.objects.remove(old); bpy.data.armatures.remove(arm)
    ob = s.copy(); ob.data = s.data.copy(); ob.name = name; ob.data.name = name
    ob.animation_data_clear()
    bpy.context.scene.collection.objects.link(ob)
    full = dict(bones)
    for k, (h, t) in bones.items():
        if k.endswith('.L'):
            full[k[:-2] + '.R'] = ((-h[0], h[1], h[2]), (-t[0], t[1], t[2]))
    for o in bpy.context.selected_objects:
        o.select_set(False)
    ob.hide_set(False); ob.select_set(True); bpy.context.view_layer.objects.active = ob
    bpy.ops.object.mode_set(mode='EDIT')
    eb = ob.data.edit_bones
    for b in eb:  # 연결 뼈는 부모 꼬리를 따라가므로 먼저 끊고 옮긴 뒤 다시 잇는다
        b['_c'] = b.use_connect; b.use_connect = False
    for k, (h, t) in full.items():
        roll = eb[k].roll
        eb[k].head = h; eb[k].tail = t; eb[k].roll = roll
    for b in eb:
        b.use_connect = bool(b['_c']); del b['_c']
    bpy.ops.object.mode_set(mode='OBJECT')
    return ob

